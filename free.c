#include "push_swap.h"
#include "libft/libft.h"
#include <stdlib.h>

void	free_str_array(char **arr)
{
	int	i;

	if (!arr)
		return ;
	i = 0;
	while (arr[i])
		free(arr[i++]);
	free(arr);
}
